"""Sync-inspector markup: the browser is handed one self-contained block.

These are pure-function tests (no Streamlit, no audio): they lock the
contract between the API payload and the drawing code — the payload rides in
a base64 attribute, every caption gets a label, and defect rows keep their
severity so the canvas can colour them.
"""
import base64
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from frontend.sync_inspector import inspector_html, summary_line


def _pay(**kw):
    pay = {
        "duration": 12.0,
        "hop": 0.05,
        "peaks": [0, 40, 90],
        "probs": [0, 88, 100],
        "speech": [[1.0, 4.0]],
        "silence": [[4.0, 6.0]],
        "segs": [[1.0, 4.0]],
        "words": [[1.1, 1.5]],
        "metrics": {"n_segments": 1, "n_speech_runs": 1, "n_warn": 0,
                    "n_info": 1, "over_silence_s": 0.0,
                    "empty_speech_s": 0.0},
        "issues": [],
        "vad_backend": "onnx",
        "curve_backend": "onnx",
    }
    pay.update(kw)
    return pay


def _segs():
    return [{"surah": 59, "ayah": 1, "start": 1.0, "end": 4.0,
             "text_ar": "سَبَّحَ لِلَّهِ", "text_en": "Whatever is in the heavens"}]


def _decoded(html):
    marker = 'data-sync="'
    i = html.index(marker) + len(marker)
    b64 = html[i:html.index('"', i)]
    return json.loads(base64.b64decode(b64).decode())


def test_payload_round_trips_through_the_data_attribute():
    html = inspector_html(_pay(), _segs())
    body = _decoded(html)
    assert body["duration"] == 12.0
    assert body["peaks"] == [0, 40, 90]
    assert body["speech"] == [[1.0, 4.0]]
    assert body["vad_backend"] == "onnx"


def test_every_caption_gets_a_label_preferring_arabic():
    segs = _segs() + [{"surah": 59, "ayah": 2, "start": 4.0, "end": 6.0,
                       "text_ar": "", "text_en": "English only"}]
    body = _decoded(inspector_html(_pay(), segs))
    assert body["labels"][0].startswith("سَبَّحَ")
    assert body["labels"][1] == "English only"


def test_block_contains_canvas_script_and_controls():
    html = inspector_html(_pay(), _segs())
    assert "<canvas></canvas>" in html
    assert "qcap-sync-fit" in html
    assert "qcap-sync-copy" in html
    assert "<script>" in html and len(html) > 5000   # the drawing code rides along
    assert "#qcap-sync" in html                      # scoped styles, no page leak


def test_issue_rows_keep_severity_and_time():
    issues = [
        {"kind": "over_silence", "sev": "warn", "t0": 4.0, "t1": 4.4,
         "seg": 0, "text": "caption holds 0.40s into a breath"},
        {"kind": "late_start", "sev": "info", "t0": 7.5, "t1": None,
         "seg": 1, "text": "starts 0.60s after the nearest word"},
    ]
    html = inspector_html(_pay(issues=issues), _segs())
    assert "sev-warn" in html and "over_silence" in html
    assert "sev-info" in html and "late_start" in html
    assert 'data-t="4.0"' in html


def test_a_clean_clip_says_so_instead_of_showing_nothing():
    html = inspector_html(_pay(issues=[]), _segs())
    assert "no timing issues found" in html


def test_summary_reports_the_evidence_sources():
    line = summary_line(_pay())
    assert "1 captions" in line
    assert "warning(s) 0" in line and "clue(s) 1" in line
    assert "VAD onnx" in line and "curve onnx" in line


def test_markup_in_the_captions_cannot_break_out_of_the_attribute():
    segs = [{"surah": 1, "ayah": 1, "start": 0.0, "end": 1.0,
             "text_ar": "</script><script>alert(1)</script>", "text_en": ""}]
    html = inspector_html(_pay(), segs)
    body = _decoded(html)
    assert body["labels"][0].startswith("</script>")   # data survives
    assert "<script>alert(1)" not in html              # and cannot run
    assert html.count("</script>") == 1


def test_scripts_cannot_trip_streamlits_dompurify_mxss_guard():
    """A silent killer: DOMPurify drops the whole script element when its text
    contains an angle bracket followed by a letter, slash or bang.

    st.html sanitizes with SAFE_FOR_XML, so a single comment like
    "the video tag is letterboxed" written with angle brackets removed the
    caption player's ENTIRE script from the page — no console error, captions
    simply stopped appearing. Every JS asset we inline must stay clear of it.
    """
    import ast
    import re

    trip = re.compile(r"<[/\w!]")
    root = os.path.dirname(os.path.abspath(__file__))

    for name in ("sync_inspector.js", "opus_proxy.js"):
        with open(os.path.join(root, "frontend", name), encoding="utf-8") as f:
            hits = trip.findall(f.read())
        assert not hits, f"{name} contains a DOMPurify tripwire: {hits}"

    # The player HTML is generated by a module-level function that runs the
    # whole Streamlit app on import, so lift just that function's AST.
    with open(os.path.join(root, "frontend", "app.py"), encoding="utf-8-sig") as f:
        tree = ast.parse(f.read())
    fn = next(n for n in tree.body
              if isinstance(n, ast.FunctionDef) and n.name == "player_html")
    ns = {"json": json, "base64": base64}
    exec(compile(ast.Module(body=[fn], type_ignores=[]),
                 "player_html", "exec"), ns)
    html = ns["player_html"](
        "http://x/m/1", [{"start": 0.0, "end": 1.0, "text_ar": "ب",
                          "text_en": "B"}], "ar", {})
    body = html.split("<script>")[1].split("</script>")[0]
    assert not trip.search(body), \
        "player script contains a DOMPurify tripwire: " + str(trip.findall(body))
